# Длинные названия раньше коротких: «Нижний Новгород» до «Новгород», «Ростов-на-Дону» до «Ростов»
_CITY_RE = re.compile(r"(?<![А-Яа-яЁё-])(" + "|".join(sorted(map(re.escape, CITIES), key=len, reverse=True))
                      + r")(?![А-Яа-яЁё])")
_REGION_RE = re.compile(r"(?<![А-Яа-яЁё])(" + "|".join(sorted(map(re.escape, REGIONS), key=len, reverse=True))
                        + r")")


